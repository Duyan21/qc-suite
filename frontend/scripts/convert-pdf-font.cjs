// One-time conversion script: decompresses the Vietnamese-subset Roboto
// WOFF2 files (already present via the @fontsource/roboto dependency) into
// raw TTF bytes, base64-encodes them, and writes a TS module jsPDF can
// register as a custom font via addFileToVFS/addFont. jsPDF's built-in
// standard fonts don't cover Vietnamese diacritics, so the exported report
// needs its own embedded font. Not part of the app build — run manually
// whenever the font needs regenerating:
//   node scripts/convert-pdf-font.cjs
const fs = require('fs')
const path = require('path')
const wawoff2 = require('wawoff2')

const SOURCES = {
  normal: 'node_modules/@fontsource/roboto/files/roboto-vietnamese-400-normal.woff2',
  bold: 'node_modules/@fontsource/roboto/files/roboto-vietnamese-700-normal.woff2',
}

async function main() {
  const entries = []
  for (const [weight, relPath] of Object.entries(SOURCES)) {
    const woff2Buffer = fs.readFileSync(path.join(__dirname, '..', relPath))
    const ttfBuffer = await wawoff2.decompress(woff2Buffer)
    const base64 = Buffer.from(ttfBuffer).toString('base64')
    entries.push(`export const ROBOTO_VIETNAMESE_${weight.toUpperCase()}_BASE64 = ${JSON.stringify(base64)}`)
    console.log(`${weight}: ${woff2Buffer.length} bytes (woff2) -> ${ttfBuffer.length} bytes (ttf)`)
  }

  const outPath = path.join(__dirname, '..', 'src/lib/fonts/robotoVietnamese.ts')
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(
    outPath,
    `// Generated by scripts/convert-pdf-font.cjs — do not edit by hand.\n// Vietnamese-subset Roboto (400/700), embedded for jsPDF report export.\n\n${entries.join('\n\n')}\n`,
  )
  console.log(`wrote ${outPath}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
